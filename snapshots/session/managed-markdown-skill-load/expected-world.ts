/** Byte-exact complete-world oracle for this scenario's lossless generated resources. */
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { constants } from 'node:fs'
import { lstat, mkdir, mkdtemp, open, realpath, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { WorkspaceSnapshotEntry } from '@deepseek-ai/dsh-session-snapshot'

const RECORD_BYTES = 20808
const RECORD_SHA256 = '370e36b083b56436abe4cfa9aa1ec61ed7fcd2bbbf4d71f4103f0072a425f1f5'
const EXPECTED_PATHS: readonly string[] = [
  'skills/managed-demo/.y-topics/8b4b7d08808feeb6d4273bfedec3396c09db4e51b58fb99c7659eeca81c8fc9b/.manifest.json',
  'skills/managed-demo/.y-topics/8b4b7d08808feeb6d4273bfedec3396c09db4e51b58fb99c7659eeca81c8fc9b/entry.txt',
  'skills/managed-demo/.y-topics/8b4b7d08808feeb6d4273bfedec3396c09db4e51b58fb99c7659eeca81c8fc9b/source/0000.txt',
  'skills/managed-demo/.y-topics/8b4b7d08808feeb6d4273bfedec3396c09db4e51b58fb99c7659eeca81c8fc9b/source/0001.txt',
  'skills/managed-demo/.y-topics/8b4b7d08808feeb6d4273bfedec3396c09db4e51b58fb99c7659eeca81c8fc9b/source/0002.txt',
  'skills/managed-demo/.y-topics/8b4b7d08808feeb6d4273bfedec3396c09db4e51b58fb99c7659eeca81c8fc9b/topics/001-setup.md',
  'skills/managed-demo/.y-topics/8b4b7d08808feeb6d4273bfedec3396c09db4e51b58fb99c7659eeca81c8fc9b/topics/002-review.md',
  'skills/managed-demo/SKILL.md',
]
const recordPath = fileURLToPath(new URL('./workspace.expected/world.json', import.meta.url))

function object(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

/**
 * Materialize eight hash-bound expected files, capture them through the ordinary oracle, and clean up.
 * @param capture - unchanged complete expected-workspace reader.
 * @param path - this scenario's committed encoded record, or an owned corruption probe.
 * @returns complete expected entries with original generated bytes unchanged.
 */
export async function readExpectedWorld(
  capture: (root: string) => Promise<WorkspaceSnapshotEntry[]>,
  path = recordPath,
): Promise<WorkspaceSnapshotEntry[]> {
  const info = await lstat(path)
  assert.ok(info.isFile() && !info.isSymbolicLink(), 'expected world must be a regular committed file')
  assert.equal(info.size, RECORD_BYTES, 'expected world record byte length')
  const descriptor = await open(path, constants.O_RDONLY)
  const buffer = Buffer.alloc(RECORD_BYTES + 1)
  let count = 0
  try {
    while (count < buffer.length) {
      const { bytesRead } = await descriptor.read(buffer, count, buffer.length - count, count)
      if (bytesRead === 0) break
      count += bytesRead
    }
  } finally { await descriptor.close() }
  assert.equal(count, RECORD_BYTES, 'expected world bounded read byte length')
  const bytes = buffer.subarray(0, count)
  assert.equal(createHash('sha256').update(bytes).digest('hex'), RECORD_SHA256, 'expected world record SHA256')
  const parsed: unknown = JSON.parse(bytes.toString('utf8'))
  assert.ok(object(parsed), 'expected world record must be an object')
  assert.deepEqual(Object.keys(parsed).sort(), ['files', 'version'])
  assert.equal(parsed.version, 1)
  assert.ok(Array.isArray(parsed.files), 'expected world files must be an array')
  assert.equal(parsed.files.length, 8, 'expected world has exactly eight files')
  const files = parsed.files.map((value: unknown) => {
    assert.ok(object(value), 'expected world file must be an object')
    assert.deepEqual(Object.keys(value).sort(), ['bytes', 'content', 'path', 'sha256'])
    if (typeof value.path !== 'string' || typeof value.content !== 'string'
      || typeof value.sha256 !== 'string' || typeof value.bytes !== 'number') {
      throw new Error('expected world file metadata is invalid')
    }
    assert.ok(!value.path.startsWith('/') && !value.path.includes('\\')
      && value.path.split('/').every(part => part !== '' && part !== '.' && part !== '..'), 'expected path is relative and safe')
    assert.equal(Buffer.byteLength(value.content), value.bytes, 'expected file byte length')
    assert.ok(value.bytes <= 25 * 1024, 'expected file is bounded')
    assert.equal(createHash('sha256').update(value.content).digest('hex'), value.sha256, 'expected file SHA256')
    return { path: value.path, content: value.content }
  })
  assert.deepEqual(files.map(file => file.path), EXPECTED_PATHS, 'expected complete global path set')
  const temporary = await mkdtemp(join(await realpath(tmpdir()), 'dsh-managed-expected-world-'))
  try {
    for (const file of files) {
      const destination = join(temporary, file.path)
      await mkdir(dirname(destination), { recursive: true })
      await writeFile(destination, file.content, { flag: 'wx', mode: 0o600 })
    }
    return await capture(temporary)
  } finally { await rm(temporary, { recursive: true, force: true }) }
}
