/** The complete message set exposed to the Desktop-owned renderer. */
export type DesktopMessages = { readonly [Key in keyof typeof en]: string }

/** Compatibility alias for callers that still pass the retired locale identifier. */
export const zh = en

/** Locale payload exposed to the Desktop-owned renderer. */
export interface DesktopLocale {
  readonly id: 'en'
  readonly messages: DesktopMessages
}

/**
 * Resolve Electron's locale and optional public display label to the English shell copy.
 * @param locale - Electron's locale identifier; retained for compatibility with older callers.
 * @param displayName - Optional configured public label; omission retains existing product names.
 * @returns the English dictionary with configured display labels.
 */
export function resolveDesktopLocale(locale: string, displayName = process.env.DSH_CLIENT_DISPLAY_NAME): DesktopLocale {
  void locale
  const resolved: DesktopLocale = { id: 'en', messages: en }
  if (displayName === undefined) return resolved
  const messages = Object.fromEntries(Object.entries(resolved.messages)
    .map(([key, value]) => [key, value.replaceAll(/Y [Hh]arness/gu, () => displayName)])) as DesktopMessages
  return { ...resolved, messages }
}

/**
 * Resolve the Desktop shell's supported language from the shared preference and OS languages.
 * Legacy non-English preferences remain accepted and resolve to English so existing profiles open normally.
 * @param preference - explicit locale.preference, or null when no language was selected.
 * @param languages - operating-system languages in preference order.
 * @returns the English dictionary.
 */
export function resolveDesktopStartupLocale(preference: string | null, languages: readonly string[]): DesktopLocale {
  void preference
  void languages
  return resolveDesktopLocale('en')
}

/** Replace named placeholders in one locale-owned message. */
export function formatDesktopMessage(
  message: string,
  values: Readonly<Record<string, string>>,
): string {
  return message.replaceAll(/\{([^{}]+)\}/gu, (placeholder, key: string) => values[key] ?? placeholder)
}

/**
 * Select copy for an ordinary downloaded-update confirmation.
 * @param messages - Selected Desktop dictionary.
 * @param version - Prepared update version, including any prerelease suffix.
 * @param platform - Operating system presenting the confirmation.
 * @returns the versioned title and installation guidance.
 */
export function desktopUpdateReadyConfirmation(
  messages: DesktopMessages,
  version: string,
  platform: string,
): { message: string; detail: string } {
  return {
    message: formatDesktopMessage(messages.updateDownloadedTitle, { version }),
    detail: platform === 'win32' ? messages.updateDownloadedDetailWindows : messages.updateDownloadedDetail,
  }
}
